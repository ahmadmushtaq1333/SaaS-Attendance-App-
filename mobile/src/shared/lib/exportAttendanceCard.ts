/**
 * exportAttendanceCard.ts
 * -----------------------
 * Generates a formatted plain-text attendance summary and
 * opens the native OS share sheet via expo-sharing.
 * No new packages required.
 */

import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

/**
 * Attendance data for a single course.
 * Shape mirrors the StudentCourse entity from
 * `@/entities/session/api/student-api`.
 */
interface CourseAttendanceSummary {
  course_name: string;
  attended_count: number;
  total_sessions: number;
  attendance_percentage: number;
  is_at_risk: boolean;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/** Right-pads a string to the given width for column alignment. */
function padEnd(str: string, width: number): string {
  return str.length >= width ? str : str + ' '.repeat(width - str.length);
}

/** Left-pads a string to the given width for numeric alignment. */
function padStart(str: string, width: number): string {
  return str.length >= width ? str : ' '.repeat(width - str.length) + str;
}

/**
 * Builds the formatted plain-text report string.
 *
 * @param courses - List of course attendance summaries.
 * @param studentName - Optional student display name.
 * @returns Formatted report as a multi-line string.
 */
function buildReportText(
  courses: CourseAttendanceSummary[],
  studentName?: string,
): string {
  const divider = '─'.repeat(50);
  const now = new Date();
  const generatedAt = now.toLocaleString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });

  const lines: string[] = [];

  // Header
  lines.push('');
  lines.push('  📋  ATTENDANCE SUMMARY REPORT');
  if (studentName) {
    lines.push(`  Student : ${studentName}`);
  }
  lines.push(`  Generated : ${generatedAt}`);
  lines.push('');
  lines.push(divider);

  if (courses.length === 0) {
    lines.push('');
    lines.push('  No course data available.');
    lines.push('');
  } else {
    // Column header
    lines.push(
      `  ${padEnd('Course', 22)} ${padStart('Attended', 8)}  ${padStart('Pct', 6)}  Status`,
    );
    lines.push(divider);

    let totalAttended = 0;
    let totalSessions = 0;

    for (const course of courses) {
      totalAttended += course.attended_count;
      totalSessions += course.total_sessions;

      const pct = `${course.attendance_percentage.toFixed(1)}%`;
      const status = course.is_at_risk ? '⚠️  AT RISK' : '✅ OK';
      const sessions = `${course.attended_count}/${course.total_sessions}`;

      // Truncate long course names gracefully
      const name =
        course.course_name.length > 22
          ? course.course_name.slice(0, 19) + '...'
          : course.course_name;

      lines.push(
        `  ${padEnd(name, 22)} ${padStart(sessions, 8)}  ${padStart(pct, 6)}  ${status}`,
      );
    }

    lines.push(divider);

    // Overall summary
    const overallPct =
      totalSessions > 0
        ? ((totalAttended / totalSessions) * 100).toFixed(1)
        : '0.0';
    const overallSessions = `${totalAttended}/${totalSessions}`;

    lines.push(
      `  ${padEnd('OVERALL', 22)} ${padStart(overallSessions, 8)}  ${padStart(overallPct + '%', 6)}`,
    );
    lines.push('');
  }

  // Footer
  lines.push(divider);
  lines.push('  Generated by Quorum — Attendance Tracker');
  lines.push(divider);
  lines.push('');

  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Generates a formatted plain-text attendance report and opens the
 * native OS share sheet so the user can save or send it.
 *
 * The report is written as a temporary `.txt` file inside the Expo cache
 * directory and passed directly to `expo-sharing`.
 *
 * @param courses - Array of course attendance summaries to include.
 * @param studentName - Optional student name shown in the report header.
 *
 * @throws {Error} If sharing is not available on the current device.
 * @throws {Error} If the temporary file could not be written.
 *
 * @example
 * await shareAttendanceSummary(courses, 'Jane Doe');
 */
export async function shareAttendanceSummary(
  courses: CourseAttendanceSummary[],
  studentName?: string,
): Promise<void> {
  // Guard: ensure sharing is supported before doing any work
  const isSharingAvailable = await Sharing.isAvailableAsync();
  if (!isSharingAvailable) {
    throw new Error(
      'Sharing is not available on this device. ' +
        'Please use a physical device or an emulator with sharing support.',
    );
  }

  // Build the report text
  const reportText = buildReportText(courses, studentName);

  // Write to a temp file in the cache directory
  const fileName = `attendance_report_${Date.now()}.txt`;
  const filePath = `${FileSystem.cacheDirectory}${fileName}`;

  await FileSystem.writeAsStringAsync(filePath, reportText, {
    encoding: FileSystem.EncodingType.UTF8,
  });

  // Open the native share sheet
  await Sharing.shareAsync(filePath, {
    mimeType: 'text/plain',
    dialogTitle: 'Share Attendance Report',
    UTI: 'public.plain-text', // iOS universal type identifier
  });
}
